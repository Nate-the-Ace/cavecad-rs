#!/usr/bin/env python3
"""Regenerates docs/CODE-INDEX.md: every crate, module and public item with file:line.

Run from the repo root:   python3 tools/make_code_index.py
CI runs it with --check and fails if the committed index is stale.
Everything is read from the source (the `//!` header of each file and the first `///` line of each
public item), so the index cannot drift from the code. To get a good entry, write a good doc line."""
import re, subprocess, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "CODE-INDEX.md"
ITEM = re.compile(r"^\s*pub(?:\([a-z]+\))?\s+(?:(?:const|async|unsafe)\s+)*(fn|struct|enum|trait|type|const|static|mod)\s+([A-Za-z_][A-Za-z0-9_]*)")

def impl_target(line):
    """The type an `impl` line is for: `impl<F: FnMut() -> u64> Foo<F> {` -> Foo; `impl Tr for Bar` -> Bar."""
    if not line.startswith("impl"):
        return None
    rest, depth, i = line[4:], 0, 0
    if rest.startswith("<"):
        for i, ch in enumerate(rest):
            depth += ch == "<"
            depth -= ch == ">" and rest[i - 1] != "-"
            if depth == 0:
                rest = rest[i + 1:]
                break
    rest = rest.strip()
    if " for " in rest:
        rest = rest.split(" for ", 1)[1]
    m = re.match(r"([A-Za-z_][A-Za-z0-9_]*)", rest)
    return m.group(1) if m else None

def files():
    out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "crates"],
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
    return sorted(f for f in out if f.endswith(".rs"))

def header(lines):
    doc = []
    for ln in lines:
        s = ln.strip()
        if s.startswith("//!"):
            doc.append(s[3:].strip())
        elif doc or s:
            break
    text = " ".join(d for d in doc if d)
    return text.split(". ")[0].rstrip(".") + "." if text else "(no header comment)"

def scan(path):
    lines = (ROOT / path).read_text().splitlines()
    items, cur_impl, cur_trait, pending = [], None, None, ""
    for n, ln in enumerate(lines, 1):
        s = ln.strip()
        if s.startswith("///"):
            pending = pending or s[3:].strip()
            continue
        if s.startswith("#[") or s.startswith("//"):
            continue
        if "#[cfg(test)]" in ln:
            break
        tgt = impl_target(ln)
        if tgt:
            cur_impl = tgt
        elif ln.startswith("}"):
            cur_impl = None
        t = re.match(r"^pub trait ([A-Za-z_][A-Za-z0-9_]*)", ln)
        if t:
            cur_trait = t.group(1)
        elif ln.startswith("}"):
            cur_trait = None
        tm = re.match(r"^    (?:async\s+)?fn ([A-Za-z_][A-Za-z0-9_]*)", ln)
        if cur_trait and tm:
            items.append((n, "fn", f"{cur_trait}::{tm.group(1)}", pending))
            pending = ""
            continue
        m = ITEM.match(ln)
        if m and not (m.group(1) == "mod" and ln.rstrip().endswith(";") and False):
            kind, name = m.groups()
            where = f"{cur_impl}::{name}" if cur_impl and kind == "fn" else name
            items.append((n, kind, where, pending))
        pending = ""
    return lines, items

def build():
    out = ["# Code index", "",
           "Generated by `tools/make_code_index.py`; do not edit by hand. Find a thing here first, then open the file at the line.", ""]
    crates = {}
    for f in files():
        parts = f.split("/")
        crates.setdefault(parts[1], []).append(f)
    out += ["## Crates", ""]
    for c, fs in crates.items():
        lib = next((x for x in fs if x.endswith("src/lib.rs")), None)
        summary = header((ROOT / lib).read_text().splitlines()) if lib else ""
        out.append(f"- **{c}**: {summary}")
    out.append("")
    for c, fs in crates.items():
        out += [f"## {c}", ""]
        for f in fs:
            lines, items = scan(f)
            rel = f.split("/", 2)[2]
            out.append(f"### `{rel}`: {header(lines)}")
            out.append("")
            for n, kind, name, doc in items:
                out.append(f"- `{kind} {name}` ({f}:{n}){': ' + doc if doc else ''}")
            out.append("")
    return "\n".join(out).rstrip() + "\n"

if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("docs/CODE-INDEX.md is stale: run python3 tools/make_code_index.py")
        print("code index is current")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
