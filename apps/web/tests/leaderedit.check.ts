import { arrowAt, withArrow, withoutArrow } from '../src/lib/leader-edit.ts';
let bad = 0;
const ok = (c: boolean, m: string) => { if (!c) { bad++; console.log('FAIL', m); } };
const one: [number, number][] = [[0, 0], [50, 20]];
const two = withArrow(one, [5, 40])!;
ok(two.length === 3 && two[1][0] === 50, 'a new arrow goes on the end, the note stays second');
ok(withArrow(one, [50, 20]) === null, 'not on the note');
ok(withArrow([[0, 0]], [1, 1]) === null, 'not without a note');
ok(withoutArrow(two, 2)!.length === 2, 'drop the extra arrow');
ok(withoutArrow(two, 0)![0][0] === 5, 'drop the first and the next becomes first');
ok(withoutArrow(two, 1) === null, 'the note cannot be dropped');
ok(withoutArrow(one, 0) === null, 'the only arrow stays');
ok(arrowAt(two, 4, 38, 10) === 2 && arrowAt(two, 49, 21, 10) === -1 && arrowAt(two, 1, 1, 10) === 0, 'press picks the arrow, never the note');
if (bad) process.exit(1);
console.log('leader edit ok');

// fastening
import { attachOf, nearestVertex, parseAttach, resolveLeaders } from '../src/lib/leader-edit.ts';
import { parseStyle, styleText } from '../src/lib/line-style-text.ts';
let bad2 = 0;
const ok2 = (c: boolean, m: string) => { if (!c) { bad2++; console.log('FAIL', m); } };
const wall = { id: 'w1', kind: 'wall', points: [[0, 0], [10, 0], [10, 10]] };
const sym = { id: 's1', kind: 'sym-stalactite', points: [[40, 40], [40, 45]] };
const lead = { id: 'L', kind: 'callout', points: [[10, 10], [80, 30]], style: '' };
const near = nearestVertex([wall, sym, lead], 'L', (p) => [p[0], p[1]], 11, 9, 5);
ok2(!!near && near[0] === 10 && near[1] === 10, 'snaps to the wall vertex');
ok2(nearestVertex([wall, sym, lead], 'L', (p) => [p[0], p[1]], 40, 45, 3) === null, 'a symbol only has its insertion point');
ok2(nearestVertex([wall, lead], 'L', (p) => [p[0], p[1]], 80, 30, 9) === null, 'never fastens to itself or another leader');
const at = attachOf([[10, 10], [80, 30], [40, 40]], [wall, sym, lead], 'L');
ok2(at === '0=w1#2,2=s1#0', 'tips on vertices are attached: ' + at);
ok2(parseAttach(at).get(2)![0] === 's1', 'attachment reads back');
const moved = { ...wall, points: [[0, 0], [10, 0], [15, 20]] };
const done = resolveLeaders([moved, sym, { ...lead, points: [[10, 10], [80, 30], [40, 40]], style: ';1.00;1.00;;;;1.00;0.0;;0=w1#2' }]);
ok2(done[2].points[0][0] === 15 && done[2].points[0][1] === 20 && done[2].points[1][0] === 80, 'the arrow follows the wall');
ok2(resolveLeaders([moved, lead]).length === 2 && resolveLeaders([moved, lead])[1] === lead, 'plain leaders are left alone');
const st = parseStyle(styleText({ ...parseStyle(''), attach: '0=w1#2' }));
ok2(st.attach === '0=w1#2', 'attach survives the style text: ' + styleText({ ...parseStyle(''), attach: '0=w1#2' }));
if (bad2) process.exit(1);
console.log('fastening ok');
